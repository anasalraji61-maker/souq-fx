export const GX: Record<LangId, GxDict> = { ar: GX_AR, 'en-US': GX_EN, ku: GX_KU };

/** MEGA G dictionary for a language (Arabic when unknown). */
export function gx(lang: LangId | string | undefined): GxDict {
  return GX[(lang as LangId) || 'ar'] || GX.ar;
}

/** Fill `{name}` placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}


/** Interface language for components outside the prop chain (terminal / chart workstation). App sets it on
 * every render before its children render, so `tl()` always matches the selected language. */
let activeLang: LangId = (() => {
  try {
    return ((typeof localStorage !== 'undefined' && (localStorage.getItem('matrix_lang') as LangId)) || 'ar');
  } catch {
    return 'ar' as LangId;
  }
})();

export function setActiveLang(lang: LangId): void {
  activeLang = lang;
}

export function getActiveLang(): LangId {
  return activeLang;
}

/** MEGA G dictionary for the active interface language. */
export function tl(): GxDict {
  return gx(activeLang);
}
