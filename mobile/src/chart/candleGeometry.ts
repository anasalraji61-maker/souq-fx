/**
 * عرض جسم الشمعة داخل عمودها.
 *
 * كان الجسم `colW − 1` (والعمود نفسه خطوة الشمعة ناقص 1px): فجوة ثابتة 2px أيّاً كان التكبير.
 * بعد التكبير على الهاتف (20 شمعة على 360px ⇒ خطوة 18px) تلتصق الأجسام جداراً واحداً ولا
 * تُقرأ حدود الشمعة؛ وعند التصغير (خطوة 4px) كان الجسم 2px والفجوة 2px فتبهت الشموع.
 * الآن الجسم ≈ 78% من الخطوة: الفجوة تكبر مع التكبير، والشموع الضيّقة تكسب بكسلها.
 *
 * `colW` عرض العمود كما يُحسب بالرسم (خطوة − 1، بحدّ أدنى 2). الناتج مقرَّب لبكسل كامل،
 * بين 2 و`colW` — لا يتجاوز العمود فلا تتراكب شمعتان متجاورتان أكثر ممّا كانتا.
 */
export function candleBodyWidth(colW: number): number {
  if (!Number.isFinite(colW) || colW <= 2) return 2;
  return Math.min(colW, Math.max(2, Math.round((colW + 1) * 0.78)));
}
