/**
 * عرض جسم الشمعة داخل عمودها.
 *
 * كان الجسم `colW − 1` (والعمود نفسه خطوة الشمعة ناقص 1px): فجوة ثابتة 2px أيّاً كان التكبير.
 * بعد التكبير على الهاتف (20 شمعة على 360px ⇒ خطوة 18px) تلتصق الأجسام جداراً واحداً ولا
 * تُقرأ حدود الشمعة؛ وعند التصغير (خطوة 4px) كان الجسم 2px والفجوة 2px فتبهت الشموع.
 * الآن الجسم ≈ 78% من الخطوة: الفجوة تكبر مع التكبير، والشموع الضيّقة تكسب بكسلها.
 *
 * `colW` عرض العمود كما يُحسب بالرسم (خطوة − 1، بحدّ أدنى 2). الناتج مقرَّب لبكسل كامل،
 * بين 2 و`colW` — لا يتجاوز العمود فلا تتراكب شمعتان متجاورتان أكثر ممّا كانتا.
 */
export function candleBodyWidth(colW: number): number {
  if (!Number.isFinite(colW) || colW <= 2) return 2;
  return Math.min(colW, Math.max(2, Math.round((colW + 1) * 0.78)));
}

/**
 * إطار جسم الشمعة المجوّفة. 1.5px ثابتاً على جسم 3–5px (الهاتف بالعرض الافتراضي، أو التصغير) يترك فراغاً 0–2px
 * ⇒ الصاعدة المجوّفة تُقرأ ممتلئة كالعادية ويضيع النوع كلّه. تحت 7px بالعرض أو الارتفاع الإطار 1px.
 */
export function hollowBorderWidth(bodyW: number, bodyH: number): number {
  return Math.min(bodyW, bodyH) >= 7 ? 1.5 : 1;
}

/** خطوة الشمعة المستهدفة بالعرض الافتراضي (بكسل) وحدّا عدد الشموع. */
export const REST_BAR_PX = 6;
export const REST_BARS_MIN = 40;
export const REST_BARS_MAX = 160;

/**
 * عدد الشموع بالعرض الافتراضي (فتح الشارت، AUTO، نقرتا محور الزمن) من عرض اللوح.
 *
 * كان 80 ثابتاً أيّاً كان العرض: على هاتف 360px (لوح ~292px) خطوة 3.6px فجسم 3px لا تُقرأ فيه الذيول،
 * وعلى لابتوب بلوح 1200px خطوة 15px — شموع ضخمة وتاريخ أربعة أيام فقط على 1H. الآن ~6px للشمعة:
 * الهاتف ~48 شمعة بجسم 5px، الرباعي على الويب (~600px) ~100 كما كان تقريباً، والشاشة الكاملة 160.
 * `plotW` غير صالح ⇒ 80 (القيمة القديمة) إلى أن يُقاس اللوح.
 */
export function restBarCount(plotW: number): number {
  if (!Number.isFinite(plotW) || plotW <= 0) return 80;
  return Math.max(REST_BARS_MIN, Math.min(REST_BARS_MAX, Math.round(plotW / REST_BAR_PX)));
}
