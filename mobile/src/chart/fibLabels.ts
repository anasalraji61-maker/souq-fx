/**
 * وسوم مستويات فيبوناتشي: **النسبة والسعر معاً**، ولا وسمين متلاصقين.
 *
 * ما كان يُعرض: `lv.toFixed(3)` وحده — «0.618»، «0.500»، «1.000». والمتداول لا يرسم
 * فيبو ليقرأ النسبة (يعرفها، هو من اختار الأداة) بل ليعرف **السعر عند 61.8%**: هناك
 * يضع الدخول أو الوقف. فكان عليه أن يتتبّع الخطّ بعينه حتى محور السعر على اليمين —
 * وهناك بالذات يزدحم المحور بوسم السعر الحيّ ووسم التقاطع، وكلاهما يُرسم فوق العلامات.
 *
 * ثلاثة قرارات:
 *
 * 1) **السعر بمنازل الأداة** عبر `formatPrice(price, symbol)` لا بتقدير من حجم الرقم:
 *    الين ثلاث منازل والذهب اثنتان واليورو خمس. الوسم يقول السعر بالصيغة التي يقرأها
 *    المتداول بسطر الشمعة وبخانة التنبيه — رقم واحد لا رقمان متقاربان.
 *
 * 2) **النسبة كنسبة مئوية مختصرة**: «61.8%» لا «0.618»، و«50%» لا «0.500». المتداول
 *    ينطقها هكذا، والصفر الزائد بـ«0.500» كان يُقرأ كخانة دقّة لا كنسبة.
 *
 * 3) **إسقاط الوسوم المتلاصقة بترتيب أهمية**، لا بترتيب المصفوفة. سبعة مستويات على
 *    ارتداد قصير بهاتف تقع ضمن عشرات البكسلات: بارتفاع 60px يتباعد الوسم ‎10px‎ والنصّ
 *    وحده أطول من ذلك ⇒ سبعة أسطر متراكبة تُقرأ ككتلة واحدة، وإضافة السعر تضاعف العرض
 *    فتزيد الأمر سوءاً. فيُحتفظ بالطرفين (0 و100% = طرفا الموجة، وهما ما رسمه المتداول
 *    بيده) ثم 61.8% و50% و38.2% ثم 78.6% و23.6%. الإسقاط بالأهمية لا بالموضع: وسم
 *    23.6% لا يزيح 61.8% لمجرّد أنه أعلى منه بالشاشة.
 *
 * الوحدة خالصة (تأخذ `yOf` و`format` كدالّتين) فتُفحص بـ`fibLabels.selftest.ts`.
 * والتنقية نفسها بـ`levelLabels.ts` — يستعملها الخطّ الأفقي أيضاً بعدما صار يحمل سعره.
 */
import { LEVEL_LABEL_GAP, thinByGap } from './levelLabels';

/**
 * مستويات الامتداد: **أهداف بعد نهاية الموجة** باتّجاهها (−27.2% و−61.8%، أي 127.2% و161.8% من طول الموجة
 * مقيسةً من بدايتها). المتداول يرسم فيبو على الدفعة ليعرف أين يدخل (الارتداد) **وأين يجني** — وبلا هذين
 * المستويين كان عليه أن يرسم أداة ثانية (أو يحسب بيده) لهدف الصفقة نفسها. بالسالب لأن 0% عند نهاية الموجة
 * (`fibLevelPrice`): السالب يقع بعدها، فالصيغة نفسها تعطي سعر الهدف للموجتين الصاعدة والهابطة بلا فرع.
 */
export const FIB_EXTENSIONS: readonly number[] = [-0.272, -0.618];

/** الامتداد (هدف) يُرسم بخطّ أخفّ من خطوط الارتداد — راجع `FIB_EXTENSIONS`. */
export function isFibExtension(level: number): boolean {
  return level < 0 || level > 1;
}

/**
 * ترتيب الأهمية عند الازدحام — الأول يبقى والأخير يُسقَط أولاً. الامتداد بعد 38.2%: هدف الصفقة أهمّ من
 * 78.6% و23.6% (قلّما يُتداوَلان)، وأقلّ من طرفي الموجة ومستويات الدخول الثلاثة.
 */
const FIB_IMPORTANCE = [0, 1, 0.618, 0.5, 0.382, -0.272, -0.618, 0.786, 0.236];

/** مستوى غير مدرج بالترتيب يقع بعد المدرجين، وبينها بقيمتها (ثبات الترتيب). */
function importanceRank(level: number): number {
  const i = FIB_IMPORTANCE.indexOf(level);
  return i === -1 ? FIB_IMPORTANCE.length + level : i;
}

/**
 * «61.8%» و«50%» و«0%» و«100%». خانة عشرية واحدة بحدّ أقصى، والصفر الزائد يُحذف —
 * فالنسب القياسية كلّها تخرج بأقصر صيغة صادقة لها. (`toFixed(1)` ثم تقليم `.0`
 * لا `toPrecision`: الأخيرة تعطي «61.8» و«50.0» بأطوال غير متّسقة.)
 */
export function fibRatioText(level: number): string {
  if (!Number.isFinite(level)) return '';
  const pct = level * 100;
  const s = Math.abs(pct).toFixed(1);
  // علامة ناقص حقيقية (U+2212) لا شرطة: بخطّ 10px تُقرأ الشرطة كفاصل «-27.2%» لا كإشارة.
  return `${pct < 0 && s !== '0.0' ? '−' : ''}${s.endsWith('.0') ? s.slice(0, -2) : s}%`;
}

export type FibLabelPlan = {
  level: number;
  price: number;
  /** موضع الخط بالبكسل داخل لوح الرسم. */
  y: number;
  /** «61.8% · 1.08432» */
  text: string;
};

/**
 * اتجاه مستويات فيبو المرسوم (وسيط `down` لـ`fibLevelPrice`): رُسم من القمّة للقاع ⇒ 0% عند القاع (نهاية الموجة).
 * `reversed` (زرّ «عكس») يقلبها — 0% عند A و100% عند B — لمن يقيس الارتداد بالاتجاه الآخر، بلا إعادة رسم الأداة.
 * مصدر واحد للرسم واللمس والوسوم، وإلا اختلف ما يُلمس عمّا يُرى.
 */
export function fibIsDown(d: { a: { price: number }; b?: { price: number }; reversed?: boolean }): boolean {
  const down = !!d.b && d.a.price > d.b.price;
  return d.reversed ? !down : down;
}

/**
 * أسعار مستويات فيبو بين قمّة الموجة وقاعها. `span = 0` (نقطتان بنفس السعر) ⇒ كل
 * المستويات على السعر نفسه — وهو الصادق. كان `hi - lo || 1` ينشر سبعة خطوط على مدى
 * **وحدة سعرية كاملة** عند ارتداد بلا ارتفاع: على اليورو ذلك عرض الشارت كلّه مرّات.
 */
export function fibLevelPrice(hi: number, lo: number, level: number, down = false): number {
  const span = hi - lo;
  const s = span > 0 ? span : 0;
  // الارتداد يُقاس من **نهاية** الموجة كـTradingView: صاعدة (رُسمت من القاع للقمّة) ⇒ 0% عند القمّة؛
  // هابطة (`down`، من القمّة للقاع) ⇒ 0% عند القاع و61.8% فوقه. كان 0% عند القمّة دائماً، فعلى موجة
  // هابطة يقع وسم «61.8%» على سعر ارتداد 38.2% فعلياً — يضع المتداول أمر البيع عند المستوى الخطأ.
  return down ? lo + s * level : hi - s * level;
}

/**
 * خطّة وسوم مستوى فيبو: السعر والموضع والنصّ لكل مستوى يتّسع له اللوح.
 * تُعاد **مرتّبة تنازلياً بالسعر** (أعلى الشاشة أولاً) لا بترتيب القبول، فترتيب
 * عناصر React ثابت بين الإطارات.
 */
export function planFibLabels(input: {
  levels: readonly number[];
  hi: number;
  lo: number;
  /** سعر ⇐ بكسل داخل اللوح. */
  yOf: (price: number) => number;
  /** سعر ⇐ نصّ بمنازل الأداة. */
  format: (price: number) => string;
  /** أقلّ تباعد رأسي مقبول بين وسمين (علوّ سطر الوسم). */
  minGapPx?: number;
  /** مواضع وسوم أهمّ على الحافّة نفسها (وسوم الخطوط الأفقية، وفيبو مرسوم قبله). */
  taken?: readonly number[];
  /** موجة هابطة (رُسمت من القمّة للقاع) ⇒ 0% عند القاع — راجع `fibLevelPrice`. */
  down?: boolean;
  /**
   * ارتفاع اللوح بالبكسل: وسم خارج `[0, plotH]` لا يُخطَّط. مستويات الامتداد تقع غالباً خارج الشاشة (الهدف
   * لم يُبلَغ بعد) — وسمها المقصوص لا يُرى، لكنه كان سيحجز مكاناً ويُسقط وسماً ظاهراً قريباً من الحافّة.
   */
  plotH?: number;
}): FibLabelPlan[] {
  const { levels, hi, lo, yOf, format } = input;
  const minGap = input.minGapPx ?? LEVEL_LABEL_GAP;
  if (!Number.isFinite(hi) || !Number.isFinite(lo)) return [];

  const candidates: FibLabelPlan[] = [];
  for (const level of levels) {
    if (!Number.isFinite(level)) continue;
    const price = fibLevelPrice(hi, lo, level, input.down);
    if (!Number.isFinite(price)) continue;
    const y = yOf(price);
    // موضع غير محسوب (مقياس لم يُهيّأ بعد) لا يُعرض بموضع مختلَق.
    if (!Number.isFinite(y)) continue;
    if (input.plotH != null && Number.isFinite(input.plotH) && (y < -1 || y > input.plotH + 1)) continue; // ±1px: خطّ على الحافّة نفسها ظاهر
    candidates.push({ level, price, y, text: `${fibRatioText(level)} · ${format(price)}` });
  }

  const kept = thinByGap(candidates, (c) => c.y, (c) => importanceRank(c.level), minGap, input.taken);
  return kept.sort((a, b) => b.price - a.price || a.level - b.level);
}
