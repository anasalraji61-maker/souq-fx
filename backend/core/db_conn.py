"""طبقة تنسيق اتصال قاعدة البيانات — ثاني خطوة هجرة آمنة من خطة إعادة الهيكلة إلى
وحدات مستقلة (راجع docs/ARCHITECTURE.md، قسم "خطة الهجرة الفورية الآمنة"، بند 2).

نقطة الاتصال الوحيدة بـSQLite لكل التطبيق (`_conn`) + مسار ملف القاعدة (`DB_PATH`).
db.py يستوردهما من هنا بدل تعريفهما محلياً — كل استدعاء `_conn()` القائم داخل db.py
يستمر بالعمل بلا أي تغيير (يُحل عبر الاستيراد بنفس اسم النطاق المحلي).

ملاحظة نطاق مهمة (تحقّق مباشر من الكود الفعلي قبل التنفيذ، لا افتراض من الخطة النظرية):
`init_db()` **لم** يُنقَل إلى هذا الملف رغم أن خطة ARCHITECTURE.md تذكره بجانب `_conn`
— قراءة db.py الفعلية أظهرت أن `init_db()` مرتبط عضوياً بمخطط SQL ودوال الترحيل
الخاصة بنطاق التطبيق (`_seed_if_empty`/`_migrate_*`) المعرَّفة بـdb.py نفسه؛ نقله كان
سيتطلّب إما استيراداً دائرياً (db_conn.py يستورد من db.py الذي يستورد من db_conn.py)
أو نقل كل دوال الترحيل أيضاً لملف يُفترض أن يبقى "اتصال خام" فقط — كلاهما يخالف مبدأ
"نقل ميكانيكي بلا تغيير سلوك" الحاكم للهجرة. `init_db()` يبقى بـdb.py عمداً كمسؤولية
طبقة مستودع البيانات (repository)، ويستخدم `_conn()` المستوردة من هنا بلا أي تغيير.
"""
from __future__ import annotations

import os
import sqlite3
from pathlib import Path

# مسار القاعدة قابل للضبط بمتغيّر بيئة — **شرط نشر لا رفاهية**.
# `docs/DEPLOYMENT.md` يشترط قرصاً دائماً (persistent volume) لـ`matrix.db` وإلا مُحي كل
# تسجيل مستخدم/تنبيه/رسالة عند كل إعادة نشر. لكن المسار كان مثبَّتاً داخل الصورة
# (`/app/matrix.db`)، ومنصّات الاستضافة (Railway/Render/Fly.io) تُركّب القرص الدائم على
# **مسار تختاره أنت** (`/data` عادةً) — ولا يمكن تركيبه فوق `/app` لأن ذلك يحجب شيفرة
# التطبيق نفسها. أي أن الشرط المكتوب بالوثيقة كان **غير قابل للتنفيذ**: يُربَط القرص،
# ويبدو النشر ناجحاً، وتُمحى قاعدة المتداولين بصمت مع كل إعادة نشر.
# بلا المتغيّر: نفس المسار السابق حرفياً — فلا يتغيّر شيء محليّاً ولا على الـVPS.
_ENV_DB_PATH = (os.getenv("MATRIX_DB_PATH") or "").strip()
DB_PATH = (
    Path(_ENV_DB_PATH).expanduser()
    if _ENV_DB_PATH
    else Path(__file__).resolve().parent.parent / "matrix.db"
)


def _conn() -> sqlite3.Connection:
    # مجلّد القرص الدائم قد يكون فارغاً عند أول إقلاع؛ بلا إنشائه يرمي sqlite
    # «unable to open database file» — رسالة لا تدلّ على السبب إطلاقاً.
    parent = DB_PATH.parent
    if not parent.is_dir():
        parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(DB_PATH)
    c.row_factory = sqlite3.Row
    return c
